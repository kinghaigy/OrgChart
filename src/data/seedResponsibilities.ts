import type { Responsibility } from '../types';

function slugify(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

const responsibilities: Responsibility[] = [];
const usedIds = new Set<string>();

/** Adds a responsibility with one or more flat tags — each responsibility is a single line. */
function add(name: string, tags: string[]) {
  let id = `resp-${slugify(name)}`;
  if (usedIds.has(id)) id = `resp-${slugify(tags[0])}-${slugify(name)}`;
  usedIds.add(id);
  responsibilities.push({ id, name, tags });
}

